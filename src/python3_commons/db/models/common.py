import uuid
import warnings
from datetime import datetime
from typing import Any, ClassVar

from python3_commons._extras import require

require('database', 'sqlalchemy')

from sqlalchemy import BIGINT, DateTime, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.ext.compiler import compiles
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.sql import expression
from sqlalchemy.sql.compiler import DDLCompiler, SQLCompiler
from sqlalchemy.sql.ddl import CreateColumn

__all__ = [
    'BaseDBModel',
    'BaseDBUUIDModel',
    'UTCNow',
]


@warnings.deprecated('UTCNow is deprecated and will be removed in 1.0; use sqlalchemy.func.now()')
class UTCNow(expression.FunctionElement[datetime]):
    """Deprecated alias, use ``func.now()``. Renders ``CURRENT_TIMESTAMP`` (a timestamptz on PostgreSQL)."""

    type = DateTime(timezone=True)
    inherit_cache = True


@compiles(UTCNow)  # ty: ignore[deprecated]  # pyright: ignore[reportDeprecated]
def utcnow(element: expression.ClauseElement, compiler: SQLCompiler, **kw: Any) -> str:  # noqa: ARG001  # compiles hook
    return 'CURRENT_TIMESTAMP'


@compiles(CreateColumn, 'postgresql')
def use_identity(element: CreateColumn, compiler: DDLCompiler, **kw: Any) -> str:
    result = (compiler.visit_create_column(element, **kw) or '').replace(
        'SERIAL', 'INT GENERATED BY DEFAULT AS IDENTITY'
    )

    return result.replace('BIGSERIAL', 'BIGINT GENERATED BY DEFAULT AS IDENTITY')


class BaseDBModel:
    # Subclasses defining their own __mapper_args__ must merge: {**BaseDBModel.__mapper_args__, ...}
    __mapper_args__: ClassVar[dict[str, Any]] = {'eager_defaults': True}

    id: Mapped[int] = mapped_column(BIGINT, primary_key=True, sort_order=-3)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), sort_order=-2
    )
    updated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), onupdate=func.now(), sort_order=-1)


class BaseDBUUIDModel:
    # Subclasses defining their own __mapper_args__ must merge: {**BaseDBUUIDModel.__mapper_args__, ...}
    __mapper_args__: ClassVar[dict[str, Any]] = {'eager_defaults': True}

    uid: Mapped[uuid.UUID] = mapped_column(UUID, primary_key=True, sort_order=-3)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), sort_order=-2
    )
    updated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), onupdate=func.now(), sort_order=-1)
