"""Timestamp defaults of the shared model mixins compile, cache and render without a timezone shift."""

import warnings
from typing import Any

import pytest
from sqlalchemy import BigInteger, Column, Integer, MetaData, String, Table, func, select, update
from sqlalchemy.dialects import postgresql, sqlite
from sqlalchemy.orm import Mapped, declarative_base, mapped_column
from sqlalchemy.schema import CreateTable

from python3_commons.db.models.common import BaseDBModel, BaseDBUUIDModel, UTCNow


@pytest.mark.parametrize('mixin', [BaseDBModel, BaseDBUUIDModel])
def test_mixin_args_and_defaults(mixin: type[BaseDBModel | BaseDBUUIDModel]) -> None:
    assert mixin.__mapper_args__ == {'eager_defaults': True}
    assert mixin.created_at.column.server_default is not None
    assert 'now()' in str(mixin.created_at.column.server_default.arg.compile(dialect=postgresql.dialect()))


@pytest.mark.parametrize(
    ('dialect', 'expected'), [(postgresql.dialect(), 'now()'), (sqlite.dialect(), 'CURRENT_TIMESTAMP')]
)
def test_func_now_compiles(dialect, expected: str) -> None:
    assert str(func.now().compile(dialect=dialect)) == expected


@pytest.mark.parametrize('dialect', [postgresql.dialect(), sqlite.dialect()])
def test_utcnow_deprecated_alias_compiles_and_caches(dialect) -> None:
    with pytest.warns(DeprecationWarning, match='1.0'):
        element = UTCNow()

    assert str(element.compile(dialect=dialect)) == 'CURRENT_TIMESTAMP'

    with warnings.catch_warnings():
        warnings.simplefilter('error')
        assert select(element)._generate_cache_key() is not None  # noqa: SLF001


def test_model_ddl_compiles_on_sqlite_and_pg() -> None:
    from sqlalchemy import MetaData, String  # noqa: PLC0415
    from sqlalchemy.orm import declarative_base, mapped_column  # noqa: PLC0415

    base = declarative_base(metadata=MetaData())

    class Item(BaseDBModel, base):
        __tablename__ = 'item'
        name: Mapped[str] = mapped_column(String)

    assert 'DEFAULT now()' in str(CreateTable(Item.__table__).compile(dialect=postgresql.dialect()))
    assert 'DEFAULT CURRENT_TIMESTAMP' in str(CreateTable(Item.__table__).compile(dialect=sqlite.dialect()))


def _probe_ddl(dialect: Any, *columns: Column[Any]) -> str:
    table = Table('probe', MetaData(), *columns)

    return str(CreateTable(table).compile(dialect=dialect))


def test_identity_hook_renders_identity_for_bigint_and_int_pk_on_postgresql() -> None:
    ddl = _probe_ddl(postgresql.dialect(), Column('id', BigInteger, primary_key=True))

    assert 'id BIGINT GENERATED BY DEFAULT AS IDENTITY' in ddl
    assert 'SERIAL' not in ddl

    ddl = _probe_ddl(postgresql.dialect(), Column('id', Integer, primary_key=True))

    assert 'id INT GENERATED BY DEFAULT AS IDENTITY' in ddl
    assert 'SERIAL' not in ddl


def test_identity_hook_leaves_non_serial_columns_and_other_dialects_alone() -> None:
    ddl = _probe_ddl(
        postgresql.dialect(), Column('id', Integer, autoincrement=False, primary_key=True), Column('n', String)
    )

    assert 'GENERATED' not in ddl
    assert 'id INTEGER NOT NULL' in ddl
    assert 'GENERATED' not in _probe_ddl(sqlite.dialect(), Column('id', BigInteger, primary_key=True))


def test_base_model_ddl_has_identity_pk_and_now_defaults_on_postgresql() -> None:
    base = declarative_base(metadata=MetaData())

    class Probe(BaseDBModel, base):
        __tablename__ = 'probe_model'

    ddl = str(CreateTable(Probe.__table__).compile(dialect=postgresql.dialect()))

    assert 'id BIGINT GENERATED BY DEFAULT AS IDENTITY' in ddl
    assert 'created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL' in ddl
    assert 'updated_at TIMESTAMP WITH TIME ZONE' in ddl
    assert 'updated_at TIMESTAMP WITH TIME ZONE DEFAULT' not in ddl


def test_uuid_model_ddl_has_now_default_and_no_identity_on_postgresql() -> None:
    base = declarative_base(metadata=MetaData())

    class UuidProbe(BaseDBUUIDModel, base):
        __tablename__ = 'probe_uuid_model'

    ddl = str(CreateTable(UuidProbe.__table__).compile(dialect=postgresql.dialect()))

    assert 'uid UUID NOT NULL' in ddl
    assert 'GENERATED' not in ddl
    assert 'created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL' in ddl


def test_updated_at_onupdate_renders_now_in_update_statement() -> None:
    base = declarative_base(metadata=MetaData())

    class Upd(BaseDBModel, base):
        __tablename__ = 'probe_upd'
        name: Mapped[str] = mapped_column(String)

    stmt = update(Upd.__table__).values(name='x')

    assert 'updated_at=now()' in str(stmt.compile(dialect=postgresql.dialect()))
